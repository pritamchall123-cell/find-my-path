import { useEffect, useState } from 'react';
import jsPDF from 'jspdf';
import confetti from 'canvas-confetti';
import axiosInstance from '../api/axiosInstance';
import PageLoader from '../components/PageLoader';
import RoadmapGenerating from '../components/RoadmapGenerating';

const stepIcons = ['🌱', '🛠️', '💪', '🚀', '🎯', '🏗️', '🏆', '🎓'];

function Roadmap() {
  const [roadmap, setRoadmap] = useState(null);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [message, setMessage] = useState('');

  const user = JSON.parse(localStorage.getItem('user') || '{}');

  const fetchRoadmap = async () => {
    try {
      const res = await axiosInstance.get('/roadmap/me');
      setRoadmap(res.data.roadmap);
    } catch (err) {
      setRoadmap(null);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchRoadmap();
  }, []);

  const handleGenerate = async () => {
    setGenerating(true);
    setMessage('');
    try {
      const res = await axiosInstance.post('/roadmap/generate');
      setRoadmap(res.data.roadmap);
      confetti({
        particleCount: 120,
        spread: 90,
        origin: { y: 0.5 },
        colors: ['#2563eb', '#4f46e5', '#f59e0b'],
      });
    } catch (err) {
      setMessage(err.response?.data?.message || 'Failed to generate roadmap. Have you set a target career?');
    } finally {
      setGenerating(false);
    }
  };

  const handleStepStatusChange = async (stepId, newStatus) => {
    try {
      const res = await axiosInstance.patch(`/roadmap/step/${stepId}`, { status: newStatus });
      setRoadmap(res.data.roadmap);
      if (newStatus === 'completed') {
        confetti({
          particleCount: 80,
          spread: 70,
          origin: { y: 0.6 },
        });
      }
    } catch (err) {
      console.error(err);
    }
  };

  const handleDownloadPDF = () => {
    if (!roadmap) return;

    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.getWidth();
    const margin = 15;
    const maxWidth = pageWidth - margin * 2;
    let y = 20;

    const addPageIfNeeded = (neededSpace = 10) => {
      if (y + neededSpace > 280) {
        doc.addPage();
        y = 20;
      }
    };

    doc.setFontSize(20);
    doc.setTextColor(37, 99, 235);
    doc.text('FindMyPath', margin, y);
    y += 10;

    doc.setFontSize(14);
    doc.setTextColor(0, 0, 0);
    doc.text(`Career Roadmap: ${roadmap.targetCareer?.name || 'Career'}`, margin, y);
    y += 6;

    doc.setFontSize(10);
    doc.setTextColor(100, 100, 100);
    doc.text(`Prepared for: ${user.name || 'Student'}`, margin, y);
    y += 5;
    doc.text(`Generated: ${new Date(roadmap.generatedAt).toLocaleDateString()}`, margin, y);
    y += 10;

    doc.setDrawColor(220, 220, 220);
    doc.line(margin, y, pageWidth - margin, y);
    y += 10;

    roadmap.steps.forEach((step, index) => {
      addPageIfNeeded(30);

      doc.setFontSize(12);
      doc.setTextColor(37, 99, 235);
      doc.text(`${index + 1}. ${step.title}`, margin, y);
      y += 6;

      doc.setFontSize(9);
      doc.setTextColor(80, 80, 80);
      const descLines = doc.splitTextToSize(step.description, maxWidth);
      doc.text(descLines, margin, y);
      y += descLines.length * 4.5 + 2;

      if (step.skills?.length > 0) {
        addPageIfNeeded(8);
        doc.setFontSize(9);
        doc.setTextColor(0, 0, 0);
        doc.text(`Skills: ${step.skills.join(', ')}`, margin, y);
        y += 5;
      }

      if (step.project) {
        addPageIfNeeded(8);
        doc.text(`Project: ${step.project}`, margin, y);
        y += 5;
      }

      if (step.estimatedEffort) {
        addPageIfNeeded(8);
        doc.setTextColor(120, 120, 120);
        doc.text(`Estimated effort: ${step.estimatedEffort}`, margin, y);
        y += 5;
      }

      doc.setFontSize(9);
      doc.setTextColor(
        step.status === 'completed' ? 34 : step.status === 'in_progress' ? 180 : 150,
        step.status === 'completed' ? 139 : step.status === 'in_progress' ? 140 : 150,
        step.status === 'completed' ? 34 : 50
      );
      doc.text(`Status: ${step.status.replace('_', ' ')}`, margin, y);
      y += 10;

      doc.setDrawColor(240, 240, 240);
      doc.line(margin, y - 4, pageWidth - margin, y - 4);
    });

    addPageIfNeeded(15);
    doc.setFontSize(8);
    doc.setTextColor(150, 150, 150);
    doc.text('Generated by FindMyPath — AI-guided career roadmap platform', margin, 290);

    doc.save(`${roadmap.targetCareer?.name || 'roadmap'}-roadmap.pdf`);
  };

  if (loading) return <PageLoader message="Loading your roadmap..." />;

  const completedCount = roadmap
    ? roadmap.steps.filter((s) => s.status === 'completed').length
    : 0;
  const overallProgress = roadmap ? Math.round((completedCount / roadmap.steps.length) * 100) : 0;

  return (
    <div className="min-h-screen bg-gray-50 p-8 max-w-2xl mx-auto">
      <div className="flex justify-between items-center mb-2 flex-wrap gap-3">
        <h1 className="text-3xl font-bold">Your Journey</h1>
        {roadmap && (
          <button
            onClick={handleDownloadPDF}
            className="bg-gray-800 text-white px-4 py-2 rounded font-semibold hover:bg-gray-900 text-sm flex items-center gap-2"
          >
            📄 Download PDF
          </button>
        )}
      </div>

      {message && (
        <div className="bg-red-100 text-red-700 p-3 rounded mb-4 text-sm">{message}</div>
      )}

      {generating && <RoadmapGenerating />}

      {!generating && !roadmap && (
        <div className="bg-white p-8 rounded-xl shadow text-center">
          <div className="text-5xl mb-4">🧭</div>
          <p className="text-gray-700 mb-6">
            Your roadmap hasn't been built yet. One click, and the AI maps out your exact path to job-ready.
          </p>
          <button
            onClick={handleGenerate}
            className="bg-gradient-to-r from-blue-600 to-indigo-600 text-white px-8 py-3 rounded-lg font-bold hover:shadow-lg transition-all hover:scale-105"
          >
            🚀 Generate My Roadmap
          </button>
        </div>
      )}

      {!generating && roadmap && (
        <>
          <div className="bg-gradient-to-br from-blue-600 to-indigo-700 text-white rounded-xl p-6 mb-8 mt-4">
            <p className="text-sm text-blue-100 mb-1">Target Career</p>
            <h2 className="text-2xl font-extrabold mb-4">{roadmap.targetCareer?.name || 'Career'}</h2>
            <div className="w-full bg-white/20 rounded-full h-3 mb-2">
              <div
                className="bg-white h-3 rounded-full transition-all duration-700"
                style={{ width: `${overallProgress}%` }}
              ></div>
            </div>
            <p className="text-sm text-blue-100">
              {completedCount}/{roadmap.steps.length} steps completed — {overallProgress}% there
            </p>
          </div>

          <div className="relative pl-10">
            <div className="absolute left-4 top-2 bottom-2 w-0.5 bg-gray-200"></div>

            {roadmap.steps.map((step, index) => {
              const isCompleted = step.status === 'completed';
              const isInProgress = step.status === 'in_progress';

              return (
                <div key={step._id} className="relative mb-6 last:mb-0">
                  <div
                    className={`absolute -left-10 top-0 w-8 h-8 rounded-full flex items-center justify-center text-sm font-bold border-4 border-gray-50 transition-all ${
                      isCompleted
                        ? 'bg-green-500 text-white'
                        : isInProgress
                        ? 'bg-amber-400 text-white'
                        : 'bg-gray-300 text-gray-600'
                    }`}
                  >
                    {isCompleted ? '✓' : index + 1}
                  </div>

                  <div
                    className={`bg-white p-5 rounded-lg shadow transition-all ${
                      isCompleted ? 'opacity-70' : 'hover:shadow-md'
                    }`}
                  >
                    <div className="flex justify-between items-start gap-2">
                      <h3 className="font-bold text-lg flex items-center gap-2">
                        <span>{stepIcons[index % stepIcons.length]}</span>
                        {step.title}
                      </h3>
                      <span
                        className={`text-xs font-semibold px-2 py-1 rounded-full whitespace-nowrap ${
                          isCompleted
                            ? 'bg-green-100 text-green-700'
                            : isInProgress
                            ? 'bg-amber-100 text-amber-700'
                            : 'bg-gray-100 text-gray-600'
                        }`}
                      >
                        {step.status.replace('_', ' ')}
                      </span>
                    </div>

                    <p className="text-gray-700 text-sm mt-2">{step.description}</p>

                    {step.skills?.length > 0 && (
                      <div className="flex flex-wrap gap-1.5 mt-3">
                        {step.skills.map((s, i) => (
                          <span key={i} className="bg-blue-50 text-blue-700 text-xs px-2 py-1 rounded-full">
                            {s}
                          </span>
                        ))}
                      </div>
                    )}

                    {step.project && (
                      <p className="text-sm mt-2">
                        <span className="font-semibold">🛠️ Project:</span> {step.project}
                      </p>
                    )}

                    {step.estimatedEffort && (
                      <p className="text-xs mt-1 text-gray-400">⏱️ {step.estimatedEffort}</p>
                    )}

                    <select
                      value={step.status}
                      onChange={(e) => handleStepStatusChange(step._id, e.target.value)}
                      className="mt-3 border rounded p-1.5 text-sm"
                    >
                      <option value="not_started">Not Started</option>
                      <option value="in_progress">In Progress</option>
                      <option value="completed">Completed</option>
                    </select>
                  </div>
                </div>
              );
            })}
          </div>

          {overallProgress === 100 && (
            <div className="bg-gradient-to-br from-amber-400 to-orange-500 text-white rounded-xl p-6 text-center mt-6">
              <div className="text-4xl mb-2">🏆</div>
              <h3 className="font-bold text-lg">You completed your entire roadmap!</h3>
              <p className="text-sm text-amber-50 mt-1">
                That's real, sustained effort. You're genuinely job-ready — time to put it to work.
              </p>
            </div>
          )}
        </>
      )}
    </div>
  );
}

export default Roadmap;