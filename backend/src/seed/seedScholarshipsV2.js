const seed = async () => {
  await connectDB();

  await Scholarship.deleteMany({});
  const allScholarships = [...centralScholarships, ...westBengalScholarships];
  for (const s of allScholarships) {
    await Scholarship.create({ ...s, slug: slugify(s.name) });
  }
  console.log(`Seeded ${allScholarships.length} scholarships (central + West Bengal).`);

  for (const sp of statePortals) {
    await StatePortal.findOneAndUpdate({ stateOrUT: sp.stateOrUT }, sp, { upsert: true });
  }
  console.log(`Seeded ${statePortals.length} state/UT portal entries.`);

  mongoose.connection.close();
};

seed();